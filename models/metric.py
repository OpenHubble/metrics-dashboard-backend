# SQLAlchemy
from sqlalchemy import DateTime, ForeignKey, Index, JSON, Uuid
from sqlalchemy.orm import Mapped, mapped_column, relationship

# UUID
import uuid

# Datetime
from datetime import datetime, timezone

# Types
from typing import Any

# Application
from base import BaseModel  # Base


# Metrics Model
class Metric(BaseModel):
    __tablename__ = "metrics"

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    host_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("hosts.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    agent_metric_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        nullable=False,
        comment="Original metric UUID generated by the agent",
    )
    collector: Mapped[str] = mapped_column(
        nullable=False,
        index=True,
    )
    collected_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        index=True,
    )
    ingested_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
    )
    metrics: Mapped[dict[str, Any]] = mapped_column(
        JSON,
        nullable=False,
    )

    host: Mapped["Host"] = relationship(
        "Host",
        back_populates="metrics",
    )


# Index
Index(
    "ix_metrics_host_collector_collected",
    Metric.host_id,
    Metric.collector,
    Metric.collected_at.desc(),
)
